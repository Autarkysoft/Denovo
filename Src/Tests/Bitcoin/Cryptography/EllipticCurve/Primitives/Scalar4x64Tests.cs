        /// <summary>
        /// test_inverse_scalar
        /// </summary>
        // These tests test the following identities:
        //
        // for x==0: 1/x == 0
        // for x!=0: x*(1/x) == 1
        // for x!=0 and x!=1: 1/(1/x - 1) + 1 == -1/(x-1)
        private static void TestInverseScalar(in Scalar4x64 x, int useVar, out Scalar4x64 _out)
        {
            Scalar4x64 l = useVar == 0 ? x.Inverse() : x.InverseVar(); // l = 1/x
            _out = l;
            if (x.IsZero)
            {
                Assert.True(l.IsZero);
                return;
            }
            Scalar4x64 t = x.Multiply(l);                   // t = x*(1/x)
            Assert.True(t.IsOne);                           // x*(1/x) == 1
            Scalar4x64 r = x.Add(Minus_One, out _);         // r = x-1
            if (r.IsZero)
            {
                return;
            }
            r = useVar == 0 ? r.Inverse() : r.InverseVar(); // r = 1/(x-1)
            l = Minus_One.Add(l, out _);                    // l = 1/x-1
            l = useVar == 0 ? l.Inverse() : l.InverseVar(); // l = 1/(1/x-1)
            l = l.Add(Scalar4x64.One, out _);               // l = 1/(1/x-1)+1
            l = r.Add(l, out _);                            // l = 1/(1/x-1)+1 + 1/(x-1)
            Assert.True(l.IsZero);                          // l == 0
        }

