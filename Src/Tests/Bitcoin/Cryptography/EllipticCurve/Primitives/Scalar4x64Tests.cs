        /// <summary>
        /// scalar_test(void)
        /// </summary>
        private static unsafe void Libsecp256k1_ScalarTest(TestRNG rng)
        {
            // Set 's' to a random scalar, with value 'snum'.
            Scalar4x64 s = Libsecp256k1_RandomScalarOrderT(rng);

            // Set 's1' to a random scalar, with value 's1num'.
            Scalar4x64 s1 = Libsecp256k1_RandomScalarOrderT(rng);

            // Set 's2' to a random scalar, with value 'snum2', and byte array representation 'c'.
            Scalar4x64 s2 = Libsecp256k1_RandomScalarOrderT(rng);
            Span<byte> c = s2.ToByteArray();

            ulong* pt = stackalloc ulong[4] { s.b0, s.b1, s.b2, s.b3 };

            {
                // Test that fetching groups of 4 bits from a scalar
                // and recursing n(i)=16*n(i-1)+p(i) reconstructs it.
                Scalar4x64 n = new(0);
                for (int i = 0; i < 256; i += 4)
                {
                    Scalar4x64 t = new(Scalar4x64.GetBitsLimb32(pt, 256 - 4 - i, 4));
                    for (int j = 0; j < 4; j++)
                    {
                        n = n.Add(n, out _);
                    }
                    n = n.Add(t, out _);
                }
                Assert.True(n.Equals(s));
            }

            {
                // Test that fetching groups of randomly-sized bits from a scalar
                // and recursing n(i)=b*n(i-1)+p(i) reconstructs it
                Scalar4x64 n = new(0);
                int i = 0;
                while (i < 256)
                {
                    int now = (int)(rng.RandInt(15) + 1);
                    if (now + i > 256)
                    {
                        now = 256 - i;
                    }
                    Scalar4x64 t = new(Scalar4x64.GetBitsVar(pt, 256 - now - i, now));
                    for (int j = 0; j < now; j++)
                    {
                        n = n.Add(n, out _);
                    }
                    n = n.Add(t, out _);
                    i += now;
                }
                Assert.True(n.Equals(s));
            }

            {
                // Test commutativity of add
                Scalar4x64 r1 = s1.Add(s2, out _);
                Scalar4x64 r2 = s2.Add(s1, out _);
                Assert.True(r1.Equals(r2));
            }

            {
                // Test add_bit
                uint bit = (uint)rng.RandBits(8);
                Scalar4x64 b = new(1);
                Assert.True(b.IsOne);
                for (int i = 0; i < bit; i++)
                {
                    b = b.Add(b, out _);
                }
                Scalar4x64 r1 = s1;
                Scalar4x64 r2 = s1;
                r1 = r1.Add(b, out bool overflow);
                if (!overflow)
                {
                    // No overflow happened
                    r2 = r2.CAddBit(bit, 1);
                    Assert.True(r1.Equals(r2));

                    // cadd is a noop when flag is zero
                    r2 = r2.CAddBit(bit, 0);
                    Assert.True(r1.Equals(r2));
                }
            }

            {
                // Test commutativity of mul
                Scalar4x64 r1 = s1.Multiply(s2);
                Scalar4x64 r2 = s2.Multiply(s1);
                Assert.True(r1.Equals(r2));
            }

            {
                // Test associativity of add
                // s1 + s2 + s == s2 + s + s1
                Scalar4x64 r1 = s1.Add(s2, out _);
                r1 = r1.Add(s, out _);
                Scalar4x64 r2 = s2.Add(s, out _);
                r2 = s1.Add(r2, out _);
                Assert.True(r1.Equals(r2));
            }

            {
                // Test associativity of mul
                // s1 * s2 * s == s2 * s * s1
                Scalar4x64 r1 = s1.Multiply(s2);
                r1 = r1.Multiply(s);
                Scalar4x64 r2 = s2.Multiply(s);
                r2 = s1.Multiply(r2);
                Assert.True(r1.Equals(r2));
            }

            {
                // Test distributitivity of mul over add
                // (s1 + s2) * s == (s1 * s) + (s2 * s)
                Scalar4x64 r1 = s1.Add(s2, out _);
                r1 = r1.Multiply(s);
                Scalar4x64 r2 = s1.Multiply(s);
                Scalar4x64 t = s2.Multiply(s);
                r2 = r2.Add(t, out _);
                Assert.True(r1.Equals(r2));
            }

            {
                // Test multiplicative identity
                Scalar4x64 r1 = s1.Multiply(Scalar4x64.One);
                Assert.True(r1.Equals(s1));
            }

            {
                // Test additive identity
                Scalar4x64 r1 = s1.Add(Scalar4x64.Zero, out _);
                Assert.True(r1.Equals(s1));
            }

            {
                // Test zero product property
                Scalar4x64 r1 = s1.Multiply(Scalar4x64.Zero);
                Assert.True(r1.Equals(Scalar4x64.Zero));
            }

            {
                // Test halving
                Scalar4x64 r = s.Add(s, out _);
                r = r.Half();
                Assert.True(r.Equals(s));
            }
        }


