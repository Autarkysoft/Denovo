        internal static int Libsecp256k1_MemCmpVar(ReadOnlySpan<byte> a, ReadOnlySpan<byte> b)
        {
            Assert.Equal(a.Length, b.Length);
            for (int i = 0; i < a.Length; i++)
            {
                int diff = a[i] - b[i];
                if (diff != 0)
                {
                    return diff;
                }
            }
            return 0;
        }

        private static int Libsecp256k1_MemCmpVar(in Scalar4x64 a, in Scalar4x64 b)
        {
            Span<byte> abytes = a.ToByteArray();
            Span<byte> bbytes = b.ToByteArray();
            return Libsecp256k1_MemCmpVar(abytes, bbytes);
        }

